"""Freeze original 1K-18K matrices and synthetic references for new key modes.

Never writes to the supplied calculator folder. Existing 4K/10K fixtures stay
independent regression references; runtime C++ needs no Python or YAML.
"""
import argparse
import contextlib
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import random
import sys
import yaml

sys.dont_write_bytecode = True
AXES = ('STREAM', 'SPEED', 'JACK', 'CHORD', 'TECH', 'HOLD')


def cases(keys):
    def note(t, lane, kind='note'):
        return dict(time=t, column=lane+1, type=kind)
    rows = {
        'stream': [note(i*.1, i%keys) for i in range(80)],
        'jack_last_lane': [note(i*.1, keys-1) for i in range(80)],
        'chord': [note(i, lane) for i in range(8) for lane in range(keys)],
        'spider': [note(i*.15, i%keys) for i in range(53)],
        'mixed_rhythm': [note(i*.1+(0 if i%4<2 else .025), (i*7+i//keys)%keys) for i in range(80)],
        'full_occupancy': [note(0,lane,'ln_start') for lane in range(keys)] + [note(8,lane,'ln_end') for lane in range(keys)],
        'staggered_holds': [note(i+lane*.004,lane,'ln_start') for i in range(8) for lane in range(keys)] +
                           [note(i+lane*.004+.32+(lane%3)*.04,lane,'ln_end') for i in range(8) for lane in range(keys)],
    }
    rng = random.Random(1800+keys)
    mixed = []
    for lane in range(keys):
        for row in range(6):
            t=row*1.2+rng.uniform(.01,.2)
            if rng.random()<.5:
                mixed += [note(t,lane,'ln_start'),note(t+rng.uniform(.1,.5),lane,'ln_end')]
            else:
                mixed.append(note(t,lane))
    rows['random_mixed'] = mixed
    return rows


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,required=True)
    parser.add_argument('--header',type=Path,required=True)
    parser.add_argument('--fixtures',type=Path,required=True)
    args=parser.parse_args()
    protected=[args.source/'new_calc.py',args.source/'config.yaml']
    hashes={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in protected}
    config=yaml.safe_load(protected[1].read_text(encoding='utf-8'))
    matrices=[]
    for key,name in [('weighted_nps','KeyWeights'),('distance_difficulty','KeyVisualDistances')]:
        source=config[key] if key=='weighted_nps' else config[key]['visual_distance_matrices']
        lines=[f'inline constexpr std::array<LaneMatrix, MaxKeys> {name} = {{{{']
        for keys in range(1,19):
            matrix=source[f'weights_{keys}k']
            assert len(matrix)==keys and all(len(row)==keys for row in matrix)
            lines.append(f'    LaneMatrix{{{{ // {keys}K')
            lines += ['        {{'+', '.join(format(float(v),'.17g') for v in row)+'}},' for row in matrix]
            lines.append('    }},')
        lines.append('}};')
        matrices += lines
    header=['#pragma once','#include "revive_native.h"',
            '// Generated by tools/generate_revive_key_support.py. No scratch variants.',
            '// Source config.yaml SHA-256: '+hashes['config.yaml'],'namespace revive {']+matrices+['}']
    with args.header.open('x',encoding='utf-8') as output: output.write('\n'.join(header)+'\n')
    spec=importlib.util.spec_from_file_location('original_revive_keys',protected[0])
    original=importlib.util.module_from_spec(spec);spec.loader.exec_module(original)
    args.fixtures.mkdir(parents=True,exist_ok=False)
    kinds={'note':0,'ln_start':1,'ln_end':2}
    count=0
    for keys in range(1,19):
        if keys in (4,10): continue
        destination=args.fixtures/str(keys);destination.mkdir()
        for name,notes in cases(keys).items():
            with contextlib.redirect_stdout(io.StringIO()):
                result=original.calculate_total_difficulty(notes,8,key_mode=keys,preset_name='qwilight_bms_ez',config=config)
            values=[8,len(notes),result['revive_difficulty'],result['revive_lv'],result['circus_rating']]
            values += [result['skill_radar'][axis] for axis in AXES]
            text=' '.join(format(v,'.17g') for v in values)+'\n'
            text+=''.join(f"{n['time']:.17g} {n['column']-1} {kinds[n['type']]}\n" for n in notes)
            (destination/(name+'.tsv')).write_text(text,encoding='ascii')
            count+=1
        print(f'{keys}K: 8 original-Python references',flush=True)
    assert hashes=={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in protected}
    (args.fixtures/'provenance.json').write_text(json.dumps(dict(source_hashes=hashes,cases=count,
        keys=[k for k in range(1,19) if k not in (4,10)],preset='qwilight_bms_ez',
        scope='fixed normal placement, no scratch, auto target; synthetic parity only'),indent=2)+'\n',encoding='utf-8')


if __name__=='__main__': main()
