"""Build the current 10K reference without rewriting historical Tryr/4/7/8K data."""
import argparse
import hashlib
import json
import math
from pathlib import Path

from build_dan_reference import bands
from prepare_revive_reference import SOURCE_NAME, course_id, load_courses


def measured_courses(root, document):
    expected = {course_id(c): c for c in document['courses']}
    metadata = json.loads((root / 'courses.json').read_text(encoding='utf-8'))
    if len(metadata) != 16 or {c['sha256'] for c in metadata} != set(expected):
        raise ValueError('Course identities do not match the 16 pinned courses')
    for row in metadata:
        course = expected[row['sha256']]
        if row['keys'] != 10 or row['rank'] != course['rank'] or row['stages'] != course['stages']:
            raise ValueError('Course stage identity or order mismatch')
    rows, seen = [], set()
    for line in (root / 'features.tsv').read_text(encoding='utf-8').splitlines():
        ident, keys, rank, group, load, baseline, nps = line.split('\t')
        if ident not in expected or ident in seen:
            raise ValueError('Unknown or duplicate feature course')
        course = expected[ident]
        if keys != '10' or int(rank) != course['rank'] or group != 'Revive2026':
            raise ValueError('Feature grade or key-count mismatch')
        values = [float(load), float(baseline), float(nps)]
        if not all(math.isfinite(v) and v > 0 for v in values):
            raise ValueError('Invalid course measurement')
        rows.append(dict(rank=course['rank'], label=course['label'],
                         course_id=ident, strain=values[0], nps=values[2],
                         chart_sha256=[s['sha256'] for s in course['stages']]))
        seen.add(ident)
    if seen != set(expected):
        raise ValueError('All 16 courses require usable feature windows')
    return sorted(rows, key=lambda r: r['rank'])


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('root', type=Path)
    parser.add_argument('--courses', type=Path, required=True)
    parser.add_argument('--header', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    parser.add_argument('--extractor', type=Path, required=True)
    parser.add_argument('--decoder', type=Path, required=True)
    args = parser.parse_args()
    document = load_courses(args.courses)
    rows = measured_courses(args.root, document)
    curve = bands(rows)
    report = dict(version=1, name=SOURCE_NAME, keys=10, courses=16, stages=64,
                  source=document['source'], matching=document['matching'],
                  statistic='Mean of strongest three overlapping 8-second pattern-load windows; 2-second step; ordered stages separated by 10-second analysis gaps',
                  metric='stars + 1.6*pattern_variety + 0.5*rhythm_complexity + 0.4*column_repeat_load + 0.1*adjacent_repeat_load',
                  reference_hold_weight=1.0, live_hold_weight=2/3,
                  assignment='Nearest reference band at midpoint boundaries; descending adjacent courses pooled and displayed as a range',
                  evaluation='Reference construction, not held-out accuracy or prediction of course clear; weights inherited from v2.8 without refitting',
                  long_note_semantics=document['long_note_semantics'],
                  labels={'15': '개전', '16': '오버조이'},
                  hashes={'course_manifest': digest(args.courses), 'features': digest(args.root / 'features.tsv'),
                          'feature_extractor': digest(args.extractor), 'bms_decoder': digest(args.decoder)},
                  bands=curve, references=rows)
    header = ['#pragma once', '#include "dan_reference.h"',
              '// Generated by tools/build_revive_reference.py; docs/revive10-reference-report.json.',
              '// Historical Dan10Reference remains in dan_reference.h for reproducibility only.',
              'namespace pattern {',
              f'inline constexpr std::array<DanBand, {len(curve)}> Revive10Reference = {{{{']
    header += [f"    {{{b['strain']:.9f}, {b['low']}, {b['high']}}}," for b in curve]
    header += ['}};', '}']
    args.header.write_text('\n'.join(header) + '\n', encoding='utf-8')
    args.report.write_text(json.dumps(report, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    print(f"courses={len(rows)} bands={len(curve)} pooled=" + str([(b['low'], b['high']) for b in curve if b['low'] != b['high']]))


if __name__ == '__main__':
    main()
